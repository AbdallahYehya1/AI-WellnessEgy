"""Per-assistant subtopic lexicons (English, Modern Standard and Egyptian Arabic).

A subtopic is a specific concern inside an assistant's field ("disagreements about money",
"long working hours and time together"). Recognising up to three of them lets the
assistant ask the model a specific question without forwarding the user's own words.

`en` terms match English words; a trailing `*` is a prefix match. `ar` terms are written
in normalised Arabic (alef forms unified, ة→ه, ى→ي) and match after common clitics are
stripped. `search_en`/`search_ar` are the words used to find evidence in the knowledge base.
Engineering vocabulary, not clinical categories.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Subtopic:
    key: str
    en: tuple[str, ...]
    ar: tuple[str, ...]
    phrase_en: str  # completes "what are practical ways to ..."
    phrase_ar: str
    search_en: str
    search_ar: str = ""
    # False for generic concerns (feelings, "partner") that must not, on their own, pull
    # this domain's sources into another assistant's answer.
    signal: bool = True


def _t(words: str) -> tuple[str, ...]:
    return tuple(words.split())


